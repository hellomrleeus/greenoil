import assert from 'node:assert/strict';
import {MapExplorer as map} from '../assets/js/map-explorer.js';
let now=0, callback;
globalThis.performance={now:()=>now};
globalThis.requestAnimationFrame=fn=>{callback=fn;return 1};
globalThis.cancelAnimationFrame=()=>{};
globalThis.window={matchMedia:()=>({matches:false})};
map.googleMap={getZoom:()=>15};
map.pinZoomScale=1;
map.animatePinZoom();
callback(120);
assert(Math.abs(map.pinZoomScale-1.1)<1e-12, 'Halfway uses linear interpolation');
callback(240);
assert.equal(map.pinZoomScale,1.2);
assert.equal(map.pinZoomFrame,null);
assert.equal(map.getPinZoomScale(1),0.6);
assert.equal(map.getPinZoomScale(22),1.4);
window.matchMedia=()=>({matches:true});
map.googleMap.getZoom=()=>13;
map.animatePinZoom();callback(0);
assert.equal(map.pinZoomScale,1);
console.log('PASS: linear zoom transition, size limits and reduced motion');
window.matchMedia=()=>({matches:false});
let scheduled=0;
globalThis.requestAnimationFrame=fn=>{scheduled++;callback=fn;return scheduled};
map.googleMap.getZoom=()=>14;
map.animatePinZoom();
const loop=callback;
now=40;
map.googleMap.getZoom=()=>15;
map.animatePinZoom();
assert.equal(scheduled,1,'Rapid zoom events keep the pending frame');
assert.equal(callback,loop);
callback(160);
assert(Math.abs(map.pinZoomScale-1.1)<1e-12);
callback(280);
assert.equal(map.pinZoomScale,1.2);
console.log('PASS: continuous zoom retargets without cancelling animation frames');
